def resolve_uuid(uuid_str: str) -> tuple[str, str]:
    """
    Returns (name, category) for a UUID string.
    Handles 16-bit short UUIDs (e.g. '180d'), full 128-bit, and proprietary UUIDs.
    """
    u = uuid_str.strip().lower()

    # Check proprietary full UUID
    if u in PROPRIETARY_UUIDS:
        name, cat = PROPRIETARY_UUIDS[u]
        return name, cat

    # Normalize to short 16-bit if it's a standard BT SIG UUID
    # Standard BT SIG base: 0000xxxx-0000-1000-8000-00805f9b34fb
    if u.endswith("-0000-1000-8000-00805f9b34fb") and u.startswith("0000"):
        short = u[4:8].upper()
    elif len(u) == 4:
        short = u.upper()
    elif len(u) == 8 and u.count("-") == 0:
        short = u[-4:].upper()
    else:
        short = None

    if short:
        if short in GATT_SERVICES:
            name, cat = GATT_SERVICES[short]
            return name, cat
        if short in GATT_CHARACTERISTICS:
            name, cat = GATT_CHARACTERISTICS[short]
            return name, cat

    return "Unknown / Proprietary", "unknown"


def get_capabilities_from_uuids(uuids: list[str]) -> list[str]:
    """Derive human-readable capability labels from a list of UUIDs."""
    categories = set()
    for uuid in uuids:
        _, cat = resolve_uuid(uuid)
        if cat != "unknown" and cat != "core" and cat != "info":
            categories.add(cat)

    caps = []
    for cat in sorted(categories):
        label = CATEGORY_CAPABILITIES.get(cat, cat.title())
        if label not in caps:
            caps.append(label)
    return caps
