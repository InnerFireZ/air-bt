@functools.lru_cache(maxsize=1)
def _get_manuf_parser():
    """Cache the manuf parser so it is only loaded once."""
    try:
        import manuf
        return manuf.MacParser()
    except Exception:
        return None


def is_random_mac(mac: str) -> bool:
    """
    Return True if the MAC address is locally administered (random/private).
    In BLE, random private addresses have bit 1 (0x02) set in the first octet.
    This means OUI lookup will never resolve them.
    """
    try:
        first_byte = int(mac.upper().replace("-", ":").split(":")[0], 16)
        return bool(first_byte & 0x02)
    except Exception:
        return False


def lookup_vendor(mac: str) -> str:
    """Return vendor name for a MAC address."""
    # Detect randomized/private MAC first — OUI lookup is meaningless for these
    if is_random_mac(mac):
        return "[Random MAC]"

    mac_upper = mac.upper().replace("-", ":").replace(".", ":")
    parts = mac_upper.split(":")
    if len(parts) < 3:
        return "Unknown"
    prefix = ":".join(parts[:3])

    # Fast-path: our table
    vendor = _OUI_TABLE.get(prefix)
    if vendor:
        return vendor

    # Slow-path: manuf full IEEE database
    parser = _get_manuf_parser()
    if parser:
        try:
            result = parser.get_manuf(mac)
            if result:
                return result
        except Exception:
            pass

    return "Unknown"
